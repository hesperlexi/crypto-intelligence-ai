/** A card. `ai`: the content is model / AI-advisor output, so the card carries the shared AI marker
 *  (an "AI" tag before the title and a thin left rule), keeping it apart from market data, alerts and risk. */
export function Card({ title, right, children, className = "", ai = false }: { title?: ReactNode; right?: ReactNode; children: ReactNode; className?: string; ai?: boolean }) {
  return (
    <section className={`panel ${ai ? "ai-card" : ""} ${className}`}>
      {(title || right) && (
        <header className="card-head flex min-h-[46px] flex-wrap items-center justify-between gap-2 border-b px-4 py-2.5">
          <h2 className="label">{ai && <AiTag />}{title}</h2>
          {right}
        </header>
      )}
      <div className="card-body p-4">{children}</div>
    </section>
  );
}

