/** notes: an optional small muted suffix per option (e.g. "paused"), with a longer explanation as its tooltip. */
export function Tabs<T extends string>({ value, options, onChange, label, notes }: { value: T; options: readonly T[]; onChange: (v: T) => void; label?: string; notes?: Partial<Record<string, readonly [string, string]>> }) {
  return (
    <Segmented value={value} label={label} upper onChange={onChange}
      options={options.map((o) => (notes?.[o] ? [o, o, notes[o]![1]] as const : o))}
      after={(o) => { const n = notes?.[o]; return n ? <span className="ml-1 text-xs font-normal normal-case text-mute">{n[0]}</span> : null; }} />
  );
}

export function Note({ children }: { children: ReactNode }) {
  return <p className="text-xs leading-relaxed text-mute">{children}</p>;
}

/** Small "ⓘ" toggle: longer detail stays hidden until tapped. Phrasing content only (spans), so it can sit inside a <p>. */
export function Info({ children, label = "More info", className = "" }: { children: ReactNode; label?: string; className?: string }) {
  const [open, setOpen] = useState(false);
  return (
    <span className={`text-xs text-mute ${className}`}>
      <button type="button" className="tap inline-flex h-6 w-6 items-center justify-center rounded-full align-middle text-sm leading-none text-mute hover:text-text"
        aria-expanded={open} aria-label={label} title={label} onClick={() => setOpen((v) => !v)}>ⓘ</button>
      {open && <span className="mt-1 block max-w-prose rounded-lg border border-glass/10 bg-ink/60 px-3 py-2 text-left leading-relaxed">{children}</span>}
    </span>
  );
}

export function Check({ ok, children }: { ok: boolean | null | undefined; children: ReactNode }) {
  return (
    <div className="flex items-start gap-2 text-sm">
      <span className={ok ? "text-bull" : ok === false ? "text-bear" : "text-mute"} aria-hidden>
        {ok ? "✓" : ok === false ? "✕" : "·"}
      </span>
      <span>
        {children} <span className="sr-only">{ok ? "(passed)" : ok === false ? "(failed)" : ""}</span>
      </span>
    </div>
  );
}
