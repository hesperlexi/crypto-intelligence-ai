/** Data that is simply not there yet (the engine has not published it): a calm wait, not an error. */
export const isNotReady = (e?: string | null) => !!e && /^(Not published yet|unknown data path)/i.test(e);

export function ErrorBox({ error, retry }: { error: string; retry?: () => void }) {
  if (isNotReady(error)) return <Empty>{error.startsWith("Not published") ? error : "Not published yet. Check back in a few minutes."}{retry && <button className="btn btn-sm" onClick={retry}>Check again</button>}</Empty>;
  return (
    <div role="alert" className="flex items-center justify-between gap-3 rounded-md border border-bear/40 bg-bear/10 px-3 py-2 text-sm text-bear">
      <span>{error}</span>
      {retry && (
        <button className="btn btn-sm" onClick={retry}>
          Retry
        </button>
      )}
    </div>
  );
}

